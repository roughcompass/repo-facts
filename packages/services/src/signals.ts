// Test substitutes

function reportSubstitutes(context: DetectorContext, signal: (kind: string) => MatchedRule[], imports: ImportGraph, summaries: readonly ServiceSummary[]): Candidate[] {
  const candidates: Candidate[] = [];
  const report = (key: string, value: Record<string, Value>, match: MatchedRule, relation?: Candidate["relation"]) => {
    context.fact({ category: "test_substitutes", key, value, basis: "observed", evidence: [match.evidence], rule: match.rule.id });
    if (relation) candidates.push({ item: { ...value, path: match.tree.path }, evidence: match.evidence, relation });
  };
  const at = (match: MatchedRule) => `${match.tree.path}:${match.tree.lines(match.node).start}`;
  const graphqlServices = summaries.filter((summary) => summary.protocol === "graphql").length;

  for (const match of signal("request-interceptor")) {
    const url = match.captures.url;
    const target = interceptedEndpoint(match.tree, url);
    report(`interceptor:${at(match)}`, { kind: "request_interceptor", library: match.rule.id === "services.substitute.nock" ? "nock" : "msw", url: url ? captureValue(url) : { kind: "absent" } }, match, (summary) => interception(target, summary));
  }
  for (const match of signal("graphql-interceptor")) {
    const operation = match.captures.operation;
    report(`interceptor:${at(match)}`, { kind: "graphql_interceptor", library: "msw", operation: operation ? captureValue(operation) : { kind: "absent" } }, match, (summary) => {
      if (summary.protocol !== "graphql") return { tie: "excluded" };
      return graphqlServices === 1 ? { tie: "inferred", association: "only_graphql_service", reasoning: "The test intercepts GraphQL operations and the repository has one GraphQL service; the handlers are not shown to match its schema." } : { tie: "possible" };
    });
  }
  // A mock server is tied through the handlers it serves, not by itself.
  for (const match of signal("mock-server")) report(`mock-server:${at(match)}`, { kind: "mock_server", library: literalText(match.captures.module) ?? literalText(match.captures.calleeModule) ?? "msw" }, match);

  for (const match of [...signal("module-mock"), ...signal("module-mock-candidate")]) {
    if (match.rule.id === "services.substitute.global-module-mock" && !globalMockReceiver(match)) continue;
    const module = literalText(match.captures.module);
    if (!module) continue;
    const relative = module.startsWith("./") || module.startsWith("../");
    const resolved = relative ? imports.resolve(match.tree.path, module) : null;
    report(`module-mock:${match.tree.path}:${module}`, { kind: "module_mock", module, ...(resolved !== null && { resolved }) }, match, (summary) => {
      if (relative) {
        if (resolved === null) return { tie: "possible" };
        return imports.reaches(callSiteFiles(summary), resolved) ? { tie: "observed", association: "mocks_call_site_module" } : { tie: "excluded" };
      }
      // Path aliases such as `@/api` are not resolved, so they could name any module.
      if (/^[@~#]\//.test(module)) return { tie: "possible" };
      return module === summary.pkg || (CLIENT_PACKAGES[summary.client] ?? []).includes(module) ? { tie: "observed", association: "mocks_client_package" } : { tie: "excluded" };
    });
  }
  for (const match of signal("fetch-stub")) {
    // A stub replaces fetch only for the code its test runs: tied through the test's own imports, possible through deeper ones.
    report(`global-stub:${at(match)}`, { kind: "global_stub", global: "fetch" }, match, (summary) => {
      if (!FETCH_CLIENTS.has(summary.client)) return NON_FETCH_CLIENTS.has(summary.client) ? { tie: "excluded" } : { tie: "possible" };
      return callSiteFiles(summary).some((file) => imports.reaches([match.tree.path], file)) ? { tie: "inferred", association: "global_fetch", reasoning: "A test that imports this service's calls replaces the global fetch they use; the stub is not shown to answer them like the service." } : { tie: "possible" };
    });
  }

  const fixtureDirectories = context.reader.entries.filter((entry) => entry.type === "tree" && !isVendored(entry.path) && FIXTURE_DIRECTORIES.has(entry.path.slice(entry.path.lastIndexOf("/") + 1)));
  for (const entry of fixtureDirectories) context.fact({ category: "test_substitutes", key: `fixtures:${entry.path}`, value: { kind: "fixture_directory", path: entry.path }, basis: "observed", evidence: [context.entry(entry, RULES.fixture)], rule: RULES.fixture });
  // A fixture file is tied only through a test file whose own substitute is tied to the service.
  const inFixtures = (path: string) => fixtureDirectories.some((entry) => path.startsWith(`${entry.path}/`));
  for (const substitute of [...candidates]) {
    for (const fixture of imports.of(substitute.evidence.path).filter(inFixtures)) {
      const entry = context.reader.entry(fixture);
      if (!entry) continue;
      candidates.push({
        item: { kind: "fixture", path: fixture },
        evidence: context.entry(entry, RULES.fixture),
        relation: (summary) => {
          const tie = substitute.relation(summary).tie;
          return tie === "observed" || tie === "inferred" ? { tie: "inferred", association: "imported_with_substitute", reasoning: "The fixture is imported by a test file whose substitute is tied to this service; it is not shown to be that substitute's data." } : { tie: "excluded" };
        },
      });
    }
  }
  return candidates;
}

/** A bare `vi.mock` or `jest.mock` refers to the test runner's global only when the file binds no such name itself. */
function globalMockReceiver(match: MatchedRule): boolean {
  const callee = ts.isCallExpression(match.node) ? unwrap(match.node.expression) : null;
  const receiver = callee && ts.isPropertyAccessExpression(callee) ? unwrap(callee.expression) : null;
  return receiver !== null && ts.isIdentifier(receiver) && (receiver.text === "jest" || receiver.text === "vi") && !match.tree.binding(receiver.text);
}

type Intercepted = ReturnType<typeof deriveEndpoint> | { kind: "any_origin"; path: string };

function interceptedEndpoint(tree: SyntaxTree, url: StaticValue | undefined): Intercepted {
  const text = literalText(url);
  // msw's `*/path` matches the path on any origin.
  if (text?.startsWith("*/")) return { kind: "any_origin", path: text.slice(1) };
  return deriveEndpoint(tree, undefined, url);
}

function interception(target: Intercepted, summary: ServiceSummary): Relation {
  const bare = summary.protocol === "http" ? summary.key : summary.key.slice(summary.protocol.length + 1);
  const byPath = (path: string | null): Relation => {
    if (path === null || summary.paths.length === 0) return { tie: "possible" };
    return summary.paths.some((own) => pathsMatch(path, own)) ? { tie: "observed", association: "intercepted_path" } : { tie: "excluded" };
  };
  switch (target.kind) {
    case "literal":
      if (summary.origin === null) return { tie: "possible" };
      return summary.origin === target.origin ? { tie: "observed", association: "intercepted_origin" } : { tie: "excluded" };
    case "relative":
      if (summary.origin !== null) return { tie: "excluded" };
      return summary.sameOrigin ? byPath(target.path) : { tie: "possible" };
    case "any_origin":
      return byPath(target.path);
    case "configured":
      return bare === `config:${target.source}:${target.key}` ? { tie: "observed", association: "intercepted_configuration_key" } : { tie: "possible" };
    default:
      return { tie: "possible" };
  }
}

// ---------------------------------------------------------------------------
// Association

function related(candidates: readonly Candidate[], summary: ServiceSummary) {
  const observed: Tie[] = [];
  const inferred: Tie[] = [];
  let possible = 0;
  for (const candidate of candidates) {
    const relation = candidate.relation(summary);
    if (relation.tie === "observed" || relation.tie === "inferred") (relation.tie === "observed" ? observed : inferred).push({ candidate, relation });
    else if (relation.tie === "possible") possible++;
  }
  return { observed, inferred, possible };
}

/** One candidate for all of a service's ties: observed only when every tie is. */
function associate(ties: readonly Tie[]): ServiceFactCandidate {
  const reasons = [...new Set(ties.flatMap((tie) => (tie.relation.tie === "inferred" ? [tie.relation.reasoning] : [])))].sort(compareCodeUnits);
  return {
    basis: reasons.length ? "inferred" : "observed",
    value: uniqueSorted(ties.map((tie) => ({ ...tie.candidate.item, association: tie.relation.association }))),
    evidence: ties.map((tie) => tie.candidate.evidence),
    rule: RULES.association,
    ...(reasons.length > 0 && { reasoning: reasons.join(" ") }),
  };
}

function serviceFact(ties: ReturnType<typeof related>, complete: boolean, surface: readonly string[], rule: string, openReason: string): ServiceFactCandidate {
  const all = [...ties.observed, ...ties.inferred];
  if (all.length) return associate(all);
  if (!complete) return { basis: "unknown", value: { reason: "Some inputs could not be searched" }, evidence: [], rule };
  if (ties.possible > 0) return { basis: "unknown", value: { reason: openReason }, evidence: [], rule };
  return { basis: "absent", value: null, evidence: [], rule, search: { surface, complete: true, skipped: [] } };
}

function callSiteFiles(summary: ServiceSummary): string[] {
  return [...new Set(summary.callSites.map((evidence) => evidence.path))];
}

/** Whether a route pattern (`:id`, `{id}`, `*`) and a request path (`{param}`) name the same route. */
export function pathsMatch(pattern: string, path: string): boolean {
  const split = (value: string) => value.split(/[?#]/)[0]!.split("/").filter(Boolean);
  const wild = (segment: string) => segment.startsWith(":") || /^\{[^}]*\}$/.test(segment) || segment === "*";
  const left = split(pattern);
  const right = split(path);
  for (let index = 0; index < left.length; index++) {
    // A trailing `*` matches the rest of the path.
    if (left[index] === "*" && index === left.length - 1) return right.length >= index;
    if (index >= right.length || !(wild(left[index]!) || wild(right[index]!) || left[index] === right[index])) return false;
  }
  return left.length === right.length;
}

