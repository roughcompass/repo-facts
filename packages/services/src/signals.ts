// Relative imports

interface ImportGraph {
  /** Resolves a relative specifier from +from+ to a committed path, or null. */
  resolve(from: string, specifier: string): string | null;
  /** Committed paths +file+ imports with relative specifiers. */
  of(file: string): string[];
  /** Whether +target+ is one of +files+ or imported directly by one of them. */
  reaches(files: readonly string[], target: string): boolean;
}

function importGraph(context: DetectorContext, trees: ReadonlyMap<string, SyntaxTree>): ImportGraph {
  const resolve = (from: string, specifier: string): string | null => {
    const segments = from.split("/").slice(0, -1);
    for (const part of specifier.split("/")) {
      if (part === "..") {
        if (segments.length === 0) return null;
        segments.pop();
      } else if (part !== "." && part !== "") segments.push(part);
    }
    const base = segments.join("/");
    // TypeScript's ESM style names the emitted `.js` file for a `.ts` source.
    const stems = /\.[cm]?js$/.test(base) ? [base, base.replace(/\.([cm]?)js$/, ".$1ts"), base.replace(/\.[cm]?js$/, ".tsx"), base.replace(/\.[cm]?js$/, ".d.ts")] : [base];
    for (const candidate of [...stems.flatMap((stem) => MODULE_EXTENSIONS.map((extension) => stem + extension)), ...MODULE_EXTENSIONS.slice(1).map((extension) => `${base}/index${extension}`)]) {
      const entry = context.reader.entry(candidate);
      if (entry && (entry.type === "file" || entry.type === "executable")) return candidate;
    }
    return null;
  };
  const graph = new Map<string, string[]>();
  for (const [path, tree] of trees) {
    const targets = new Set<string>();
    for (const statement of tree.file.statements) {
      const specifier = (ts.isImportDeclaration(statement) || ts.isExportDeclaration(statement)) && statement.moduleSpecifier && ts.isStringLiteral(statement.moduleSpecifier) ? statement.moduleSpecifier.text : null;
      const resolved = specifier && (specifier.startsWith("./") || specifier.startsWith("../")) ? resolve(path, specifier) : null;
      if (resolved) targets.add(resolved);
    }
    graph.set(path, [...targets].sort(compareCodeUnits));
  }
  return {
    resolve,
    of: (file) => graph.get(file) ?? [],
    reaches: (files, target) => files.some((file) => file === target || (graph.get(file) ?? []).includes(target)),
  };
}

