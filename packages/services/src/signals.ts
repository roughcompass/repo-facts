function groupBy<T>(items: readonly T[], key: (item: T) => string): [string, T[]][] {
  const groups = new Map<string, T[]>();
  for (const item of items) {
    const group = groups.get(key(item));
    if (group) group.push(item);
    else groups.set(key(item), [item]);
  }
  return [...groups.entries()].sort(([a], [b]) => compareCodeUnits(a, b));
}

function uniqueSorted(values: readonly Value[]): Value[] {
  const seen = new Map<string, Value>();
  for (const value of values) seen.set(JSON.stringify(value), value);
  return [...seen.entries()].sort(([a], [b]) => compareCodeUnits(a, b)).map(([, value]) => value);
}
